/*
  Chala Kheluya — core schema (phase 1)

  Tables
    puzzle_types      Any number of puzzle types (7 seeded). Not tied to weekdays.
    puzzles           The catalog. Each puzzle has a permanent number (kheluya.in/<number>),
                      a live date, and its files in the "puzzles" storage bucket.
    play_events       Anonymous counter events: opened, started, completed, shared, arrived, left.
    subscribers       Notify-me list (WhatsApp number + consent).
    contact_messages  Contact form.
    site_settings     On/off switches and simple values.
    admin_users       Who may use /admin.

  Security
    Visitors (anon) can read active types and puzzles that are live today or earlier (India time),
    read public settings, and only INSERT into play_events, subscribers and contact_messages.
    Everything else requires an admin.
*/

-- ---------- helpers ----------
create or replace function public.ist_today() returns date
language sql stable as $$ select (now() at time zone 'Asia/Kolkata')::date $$;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid())
$$;

create policy "admins read admins" on public.admin_users
  for select to authenticated using (public.is_admin());

-- First signed-in user may claim admin, only while no admin exists.
create or replace function public.admin_exists() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admin_users)
$$;

create or replace function public.claim_first_admin() returns boolean
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return false; end if;
  if exists (select 1 from public.admin_users) then return false; end if;
  insert into public.admin_users(user_id) values (auth.uid());
  return true;
end $$;

grant execute on function public.admin_exists() to anon, authenticated;
grant execute on function public.claim_first_admin() to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- puzzle types ----------
create table if not exists public.puzzle_types (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name_mr text not null,
  name_en text not null,
  about_mr text not null default '',
  about_en text not null default '',
  how_mr text not null default '',
  how_en text not null default '',
  tile text not null default 'क',
  color text not null default '#F39200',
  card_image_path text,
  sort_order int not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.puzzle_types enable row level security;

create policy "anyone reads active types" on public.puzzle_types
  for select to anon, authenticated using (is_active or public.is_admin());
create policy "admins write types" on public.puzzle_types
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------- puzzles ----------
create table if not exists public.puzzles (
  id uuid primary key default gen_random_uuid(),
  number int generated by default as identity (start with 1) unique,
  type_id uuid not null references public.puzzle_types(id) on delete restrict,
  name_mr text not null,
  name_en text not null default '',
  about_mr text not null default '',
  about_en text not null default '',
  keywords text not null default '',            -- English-letter search words
  difficulty text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  time_mr text not null default '',             -- e.g. १०–१५ मिनिटे
  time_en text not null default '',             -- e.g. 10–15 min
  live_date date,
  status text not null default 'draft' check (status in ('draft','live','archived')),
  file_folder text,                             -- storage path prefix, e.g. 12/v1
  entry_file text,                              -- e.g. index.html
  file_version int not null default 0,
  card_image_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists puzzles_live_idx on public.puzzles (status, live_date desc);
create index if not exists puzzles_type_idx on public.puzzles (type_id);
alter table public.puzzles enable row level security;

create policy "anyone reads live puzzles" on public.puzzles
  for select to anon, authenticated
  using ((status = 'live' and live_date is not null and live_date <= public.ist_today()) or public.is_admin());
create policy "admins write puzzles" on public.puzzles
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger puzzles_touch before update on public.puzzles for each row execute function public.touch_updated_at();
create trigger types_touch before update on public.puzzle_types for each row execute function public.touch_updated_at();

-- ---------- play events ----------
create table if not exists public.play_events (
  id bigint generated always as identity primary key,
  puzzle_id uuid not null references public.puzzles(id) on delete cascade,
  player_id uuid not null,                      -- random id kept on the phone
  session_id uuid not null,                     -- one per page load
  event text not null check (event in ('opened','started','completed','shared','arrived','left')),
  channel text check (channel is null or channel in ('whatsapp','facebook','instagram','copy','native','other')),
  source text check (source is null or source in ('puzzle','page')),
  ref text check (ref is null or length(ref) <= 16),
  value_ms int check (value_ms is null or (value_ms >= 0 and value_ms <= 86400000)),
  mistakes int check (mistakes is null or (mistakes >= 0 and mistakes < 10000)),
  hints int check (hints is null or (hints >= 0 and hints < 10000)),
  created_at timestamptz not null default now()
);
create index if not exists play_events_puzzle_idx on public.play_events (puzzle_id, event, created_at);
create index if not exists play_events_time_idx on public.play_events (created_at);
alter table public.play_events enable row level security;

create policy "anyone records events" on public.play_events
  for insert to anon, authenticated with check (true);
create policy "admins read events" on public.play_events
  for select to authenticated using (public.is_admin());
create policy "admins delete events" on public.play_events
  for delete to authenticated using (public.is_admin());

-- ---------- subscribers ----------
create table if not exists public.subscribers (
  id uuid primary key default gen_random_uuid(),
  name text not null default '' check (length(name) <= 120),
  phone text not null check (phone ~ '^[0-9+ ]{8,16}$'),
  city text not null default '' check (length(city) <= 80),
  interest text not null default 'puzzles' check (interest in ('puzzles','book','both')),
  source_page text not null default '' check (length(source_page) <= 120),
  consent boolean not null check (consent),
  created_at timestamptz not null default now()
);
alter table public.subscribers enable row level security;
create policy "anyone subscribes" on public.subscribers for insert to anon, authenticated with check (consent);
create policy "admins manage subscribers" on public.subscribers
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------- contact messages ----------
create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null default '' check (length(name) <= 120),
  phone text not null default '' check (length(phone) <= 20),
